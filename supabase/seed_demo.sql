-- ============================================================================
--  seed_demo.sql — สร้างชุดคำถามตัวอย่าง 8 ข้อ ให้บัญชีผู้จัดของคุณ
--  วิธีใช้: สมัครบัญชีในหน้าเว็บก่อน → แก้อีเมลด้านล่าง → รันใน SQL Editor
-- ============================================================================
do $$
declare
  v_email text := 'you@example.com';   -- ← แก้เป็นอีเมลบัญชีผู้จัดของคุณ
  v_uid   uuid;
  v_quiz  uuid;
begin
  select id into v_uid from auth.users where lower(email) = lower(v_email);
  if v_uid is null then
    raise exception 'ไม่พบผู้ใช้ % — สมัครบัญชีก่อนแล้วรันอีกครั้ง', v_email;
  end if;

  select id into v_quiz from public.quizzes
   where owner_id = v_uid and title = 'ตัวอย่าง: ความรู้รอบตัว';

  if v_quiz is null then
    insert into public.quizzes (owner_id, title, description, emoji)
    values (v_uid, 'ตัวอย่าง: ความรู้รอบตัว', 'ชุดทดลอง 8 ข้อ ไว้ลองระบบก่อนใช้จริง', '🧠')
    returning id into v_quiz;

    insert into public.questions (quiz_id, position, prompt, options, correct_index, time_limit) values
      (v_quiz, 0, 'แม่น้ำสายใดยาวที่สุดในประเทศไทย?',
        '["แม่น้ำเจ้าพระยา","แม่น้ำชี","แม่น้ำมูล","แม่น้ำปิง"]', 1, 20),
      (v_quiz, 1, 'ประเทศไทยมีกี่จังหวัด?', '["75","76","77","78"]', 2, 15),
      (v_quiz, 2, 'อวัยวะใดมีพื้นที่ผิวมากที่สุดในร่างกายมนุษย์?',
        '["ตับ","ผิวหนัง","ปอด","หัวใจ"]', 1, 20),
      (v_quiz, 3, '1 กิโลไบต์ (KB) ตามมาตรฐานทศนิยมเท่ากับกี่ไบต์?',
        '["100","512","1000","1024"]', 2, 20),
      (v_quiz, 4, 'จังหวัดใดได้ชื่อว่าเมืองสามหมอก?',
        '["เชียงราย","แม่ฮ่องสอน","น่าน","เลย"]', 1, 15),
      (v_quiz, 5, 'แสงสีแดงผสมกับแสงสีเขียวได้สีใด?',
        '["น้ำเงิน","เหลือง","ม่วง","ขาว"]', 1, 20),
      (v_quiz, 6, 'องค์กรใดกำหนดมาตรฐานของเว็บ (WWW)?',
        '["ISO","IEEE","W3C","ICANN"]', 2, 20),
      (v_quiz, 7, 'สัตว์เลี้ยงลูกด้วยนมชนิดใดบินได้?',
        '["นกกระจอก","ค้างคาว","กระรอกบิน","ผีเสื้อ"]', 1, 15);
  end if;
end $$;
